export const getEuropeanActivityImage = (
  title: string,
  category: string,
  address: string = "",
  description: string = "",
  location: string = "",
  id?: number
): string => {
  // 1. First check for exact activity name match for highest priority assignments
  const lowercaseTitle = title?.toLowerCase() || '';
  if (specificActivityImages[lowercaseTitle]) {
    return specificActivityImages[lowercaseTitle];
  }
  
  // 2. Check for landmark matches
  const landmarkMatch = findMatchInDictionary(title + " " + location + " " + address, europeanLandmarkImages);
  if (landmarkMatch) return landmarkMatch;
  
  // 3. Check for museum matches
  if (category?.toLowerCase().includes("museum") || category?.toLowerCase().includes("kunst") || 
      lowercaseTitle.includes("museum") || lowercaseTitle.includes("galerie")) {
    const museumMatch = findMatchInDictionary(title + " " + location, europeanMuseumImages);
    if (museumMatch) return museumMatch;
  }
  
  // 4. Check for water-related activities (lakes, beaches)
  if (category?.toLowerCase().includes("see") || lowercaseTitle.includes("see") || 
      lowercaseTitle.includes("strand") || lowercaseTitle.includes("schwimm")) {
    const waterMatch = findMatchInDictionary(title + " " + location, europeanWaterImages);
    if (waterMatch) return waterMatch;
    
    // Improved contextual matching for water activities based on location
    if (location?.toLowerCase().includes("berlin")) {
      return europeanWaterImages["wannsee"] || europeanWaterImages["schlachtensee"];
    } else if (location?.toLowerCase().includes("münchen") || location?.toLowerCase().includes("munich")) {
      return europeanWaterImages["starnberger see"];
    } else {
      // Ensure water activities always get an appropriate water image
      return europeanCategoryImages["See"] || europeanWaterImages["bodensee"];
    }
  }
  
  // 5. Check for nature activities (parks, gardens, mountains)
  if (category?.toLowerCase().includes("natur") || lowercaseTitle.includes("park") || 
      lowercaseTitle.includes("garten") || lowercaseTitle.includes("wald")) {
    const natureMatch = findMatchInDictionary(title + " " + location, europeanNatureImages);
    if (natureMatch) return natureMatch;
  }
  
  // 6. Check for cultural activities (theaters, concerts, workshops)
  if (category?.toLowerCase().includes("kultur") || category?.toLowerCase().includes("theater") || 
      lowercaseTitle.includes("workshop") || lowercaseTitle.includes("konzert") || 
      lowercaseTitle.includes("oper")) {
    const cultureMatch = findMatchInDictionary(title + " " + description, europeanCultureImages);
    if (cultureMatch) return cultureMatch;
  }
  
  // 7. Check for markets and food
  if (category?.toLowerCase().includes("markt") || category?.toLowerCase().includes("gastronomie") || 
      lowercaseTitle.includes("markt") || lowercaseTitle.includes("restaurant")) {
    const marketMatch = findMatchInDictionary(title + " " + location, europeanMarketFoodImages);
    if (marketMatch) return marketMatch;
  }
  
  // 8. Check for sports and recreation
  if (category?.toLowerCase().includes("sport") || lowercaseTitle.includes("sport") || 
      lowercaseTitle.includes("tour") || lowercaseTitle.includes("klettern")) {
    const sportMatch = findMatchInDictionary(title + " " + description, europeanSportImages);
    if (sportMatch) return sportMatch;
  }
  
  // 9. Check for special activities (workshops, experiences)
  if (lowercaseTitle.includes("workshop") || lowercaseTitle.includes("kurs") || 
      lowercaseTitle.includes("führung") || lowercaseTitle.includes("tour")) {
    const specialMatch = findMatchInDictionary(title, europeanSpecialActivityImages);
    if (specialMatch) return specialMatch;
    
    // Ensure workshop activities get a workshop image
    if (lowercaseTitle.includes("kunst")) {
      return europeanSpecialActivityImages["kunstworkshop"];
    } else if (lowercaseTitle.includes("theater")) {
      return europeanSpecialActivityImages["theater-workshop für anfänger"];
    }
  }
  
  // 10. Use ID-based deterministic but appropriate assignment for unique images
  if (id) {
    // Group images by category for better matches
    let appropriateImages: string[] = [];
    
    // Select image pool based on content
    if (category?.toLowerCase().includes("kunst") || lowercaseTitle.includes("kunst")) {
      appropriateImages = Object.values(europeanMuseumImages);
    } 
    else if (category?.toLowerCase().includes("see") || lowercaseTitle.includes("see") || lowercaseTitle.includes("strand")) {
      appropriateImages = Object.values(europeanWaterImages);
    }
    else if (category?.toLowerCase().includes("natur") || lowercaseTitle.includes("park") || lowercaseTitle.includes("garten")) {
      appropriateImages = Object.values(europeanNatureImages);
    }
    else if (category?.toLowerCase().includes("theater") || lowercaseTitle.includes("theater")) {
      appropriateImages = Object.values(europeanCultureImages);
    }
    else if (category?.toLowerCase().includes("workshop") || lowercaseTitle.includes("workshop")) {
      appropriateImages = [
        europeanSpecialActivityImages["workshop"],
        europeanSpecialActivityImages["kunstworkshop"],
        europeanCultureImages["kunstworkshop"],
        europeanSpecialActivityImages["theater-workshop für anfänger"]
      ];
    }
    else {
      // General images for other categories
      appropriateImages = [
        ...Object.values(europeanLandmarkImages),
        ...Object.values(europeanNatureImages),
        ...Object.values(europeanCultureImages)
      ];
    }
    
    // Ensure we have at least one image
    if (appropriateImages.length === 0) {
      appropriateImages = Object.values(europeanCategoryImages);
    }
    
    // Ensure each activity with the same ID gets the same image from the appropriate category
    const imageIndex = Math.abs(id) % appropriateImages.length;
    return appropriateImages[imageIndex];
  }
  
  // 11. Fall back to category-based image when no better match is found
  const categoryKey = category || "default";
  return europeanCategoryImages[categoryKey] || europeanCategoryImages["default"];
};
